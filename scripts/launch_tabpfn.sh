#!/usr/bin/env bash
set -Eeuo pipefail
if [[ $# -lt 2 || $# -gt 3 ]]; then echo "Usage: $0 <GPU_CONNECTION_FILE> <EXP_ID> [EXPERIMENT_CONFIG]" >&2; exit 2; fi
connection_file="$1";exp_id="$2"
project_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
orchestrator="/home/mlops/gpu-orchestrator"
token_file="$orchestrator/secrets/tabpfn_token"
experiment_config="${3:-$project_root/experiments/tabpfn.env}"
[[ -f "$connection_file" ]] || { echo "Missing connection file" >&2; exit 1; }
[[ -f "$token_file" ]] || { echo "Missing $token_file" >&2; exit 1; }
[[ -f "$experiment_config" ]] || { echo "Missing experiment config" >&2; exit 1; }
[[ "$(stat -c %a "$token_file")" == 600 ]] || { echo "tabpfn_token must have mode 600" >&2; exit 1; }
# The connection file is generated by gpu-orchestrator and contains trusted shell assignments.
# shellcheck disable=SC1090
source "$connection_file"
ssh_opts=(-i "$SSH_KEY" -p "$PORT" -o BatchMode=yes -o StrictHostKeyChecking=accept-new)
ssh "${ssh_opts[@]}" "$REMOTE_USER@$HOST" 'mkdir -p /root/.config/poi && chmod 700 /root/.config/poi'
scp -i "$SSH_KEY" -P "$PORT" -o BatchMode=yes -o StrictHostKeyChecking=accept-new \
  "$token_file" "$REMOTE_USER@$HOST:/root/.config/poi/tabpfn_token"
ssh "${ssh_opts[@]}" "$REMOTE_USER@$HOST" 'chmod 600 /root/.config/poi/tabpfn_token'
cleanup_token() {
  if [[ "${preserve_token:-0}" == 1 ]]; then
    echo "Remote experiment is still active; retaining its mode-600 token until the next launch or instance teardown" >&2
    return
  fi
  ssh "${ssh_opts[@]}" "$REMOTE_USER@$HOST" 'rm -f /root/.config/poi/tabpfn_token' || true
}
trap cleanup_token EXIT
launch_status=0
GPU_CONNECTION_FILE="$connection_file" EXPERIMENT_CONFIG="$experiment_config" \
  "$orchestrator/scripts/launch_experiment.sh" "$exp_id" || launch_status=$?
if (( launch_status != 0 )); then
  experiment_status="$($orchestrator/scripts/status_experiment.sh \
    "$HOST" "$PORT" poi "$exp_id" 2>&1 || true)"
  if grep -q '^RUN ACTIVE' <<< "$experiment_status"; then
    preserve_token=1
  fi
  printf '%s\n' "$experiment_status" >&2
  exit "$launch_status"
fi
